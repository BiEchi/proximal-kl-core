import asyncio
import atexit
import multiprocessing as mp
import os
import threading
from collections.abc import Callable
from concurrent.futures import ProcessPoolExecutor
from concurrent.futures.process import BrokenProcessPool
from functools import partial

# Default 'fork' inherits the rollout worker's huge PyTorch/SGLang heap into
# every reward worker. Even when the rewards are tiny and the pool is idle,
# CoW page duplication grows each worker to >100 GB after an hour, eventually
# tripping Ray's 98% host-RAM kill. 'spawn' starts each worker via exec() so
# it begins with ~50 MB instead of inheriting parent state. (2026-06-02 fix
# for repeated host-OOM kills in our DAPO runs.)
_MP_SPAWN_CTX = mp.get_context("spawn")

from areal.utils import logging

logger = logging.getLogger("RewardAPI")


def _get_device_count_safely() -> int:
    """
    Safely get device count without initializing CUDA context.
    """
    gpu_types = ["nvidia", "davinci"]
    try:
        if os.path.exists("/dev"):
            for gpu_type in gpu_types:
                devices = [
                    f
                    for f in os.listdir("/dev")
                    if f.startswith(gpu_type) and f[len(gpu_type) :].isdigit()
                ]
                if devices:
                    return len(devices)
    except (OSError, ValueError) as e:
        # /dev doesn't exist or can't read (e.g., Windows, macOS)
        logger.debug(f"Could not read device list from /dev, using fallback: {e}")

    # Fallback: assume 8 devices for cautious max_workers calculation
    return 8


def reward_fn(
    prompt: str,
    completions: str,
    prompt_ids: list[int],
    completion_ids: list[int],
    **kwargs,
):
    """This function is a placeholder for the reward function that will be used in the RLVR pipeline.

    In general, there's no restriction on the signature and implementation of this function in customized rollout workflows.
    It would be convinent to follow this signature and directly use it in our predefined rollout workflows.

    :param prompt: The string representing the task to be completed.
    :param completions: The string representing the trajectory generated by the model.
    :param prompt_ids: The token IDs of the prompt.
    :param completion_ids: The token IDs of the trajectory generated by the model.
    :param kwargs: Other attributes of the data in the dataset, such as solutions, input_outputs, etc.
        Any other attributes in the dataset will be passed as keyword arguments to this function.
    :rtype: float
    """


class AsyncRewardWrapper:
    """Wraps a synchronous reward function for async execution with timeout and retries.

    Executors are shared by ``max_workers`` key and cleaned up via ``atexit``.
    Includes automatic recovery from broken process pools.

    The reward function and its arguments must be picklable since they
    are dispatched to worker processes via ``ProcessPoolExecutor``.
    """

    _executors: dict[int, ProcessPoolExecutor] = {}
    _capacities: dict[int, asyncio.Semaphore] = {}
    _lock = threading.Lock()
    _atexit_registered = False

    def __init__(
        self,
        reward_fn: Callable,
        timeout_seconds: float | None = None,
        max_workers: int | None = None,
        max_retries: int = 3,
    ):
        self.reward_fn = reward_fn
        if timeout_seconds is None:
            # AREAL_REWARD_TIMEOUT_SECONDS lets rollout-debug runs bump the
            # asyncio wait_for timeout above the 15 s default without touching
            # production callers. Default preserves prior behavior.
            timeout_seconds = float(
                os.environ.get("AREAL_REWARD_TIMEOUT_SECONDS", "15")
            )
        self.timeout_seconds = timeout_seconds
        max_retries_env = os.environ.get("AREAL_REWARD_MAX_RETRIES")
        if max_retries_env is not None:
            max_retries = int(max_retries_env)
        max_workers_env = os.environ.get("AREAL_REWARD_MAX_WORKERS")
        if max_workers_env is not None:
            max_workers = int(max_workers_env)
        if max_workers is None:
            cpu_count = os.cpu_count() or 1
            device_count = _get_device_count_safely()
            max_workers = max((cpu_count // device_count) // 2, 1)
        self.max_workers = max_workers
        self.max_retries = max_retries
        self._executor_key = max_workers
        with self._lock:
            if self._executor_key not in self._executors:
                # The math verifier isolates parser state in its own scorer
                # subprocess and kills only that subprocess on a hard timeout.
                # Recycling this outer pool creates synchronized heavy-import
                # storms across rollout workers and is no longer necessary.
                self._executors[self._executor_key] = ProcessPoolExecutor(
                    max_workers=max_workers,
                    mp_context=_MP_SPAWN_CTX,
                )
                self._capacities[self._executor_key] = asyncio.Semaphore(max_workers)
            self._capacity = self._capacities[self._executor_key]
            if not AsyncRewardWrapper._atexit_registered:
                atexit.register(AsyncRewardWrapper._atexit_shutdown_all)
                AsyncRewardWrapper._atexit_registered = True

    @classmethod
    def _atexit_shutdown_all(cls):
        """Shut down all executors before ``_python_exit`` to prevent
        worker processes deadlocking in ``_finalize_join``.
        Must use ``wait=True`` so the result queue is fully drained.
        """
        with cls._lock:
            for executor in cls._executors.values():
                try:
                    executor.shutdown(wait=True, cancel_futures=True)
                except Exception as e:
                    logger.warning(f"Error shutting down executor at exit: {e}")
            cls._executors.clear()
            cls._capacities.clear()

    @classmethod
    def debug_state(cls) -> dict[str, dict[str, int | None]]:
        """Return a non-mutating snapshot of shared reward executor capacity."""
        with cls._lock:
            state: dict[str, dict[str, int | None]] = {}
            for key, executor in cls._executors.items():
                capacity = cls._capacities.get(key)
                waiters = getattr(capacity, "_waiters", None)
                processes = getattr(executor, "_processes", None) or {}
                state[str(key)] = {
                    "capacity_available": getattr(capacity, "_value", None),
                    "capacity_waiters": len(waiters) if waiters is not None else 0,
                    "pending_work": len(
                        getattr(executor, "_pending_work_items", None) or {}
                    ),
                    "processes": len(processes),
                    "processes_alive": sum(
                        int(process.is_alive()) for process in processes.values()
                    ),
                }
            return state

    @classmethod
    def _recreate_executor(
        cls,
        executor_key: int,
        max_workers: int,
        broken: ProcessPoolExecutor,
    ) -> ProcessPoolExecutor | None:
        with cls._lock:
            current = cls._executors.get(executor_key)
            if current is not broken:
                return current
            try:
                broken.shutdown(wait=False)
            except Exception as e:
                logger.warning(f"Error shutting down broken executor: {e}")
            try:
                new_executor = ProcessPoolExecutor(
                    max_workers=max_workers,
                    mp_context=_MP_SPAWN_CTX,
                )
            except Exception:
                logger.exception("Failed to create replacement ProcessPoolExecutor")
                cls._executors.pop(executor_key, None)
                return None
            cls._executors[executor_key] = new_executor
            logger.info(f"Recreated ProcessPoolExecutor with {max_workers} workers")
            return new_executor

    async def __call__(self, *args, **kwargs) -> float:
        for attempt in range(self.max_retries + 1):
            is_last = attempt == self.max_retries
            capacity_acquired = False
            # Queue pressure is not a reward failure. The execution timeout
            # starts only after a worker slot becomes available; rollout-level
            # cancellation remains the upper bound for waiting callers.
            await self._capacity.acquire()
            capacity_acquired = True
            future = None
            release_capacity = True
            try:
                executor = self._executors.get(self._executor_key)
                if executor is None:
                    raise RuntimeError("ProcessPoolExecutor has been shut down")
                future = asyncio.get_running_loop().run_in_executor(
                    executor,
                    partial(self.reward_fn, *args, **kwargs),
                )
                # Shield keeps the underlying process future observable after
                # timeout so its capacity is not prematurely reused.
                return await asyncio.wait_for(
                    asyncio.shield(future), timeout=self.timeout_seconds
                )
            except TimeoutError:
                if future is not None and not future.done():
                    future.add_done_callback(lambda _: self._capacity.release())
                    release_capacity = False
                logger.warning(
                    f"Computing reward timeout after {self.timeout_seconds}s "
                    f"(attempt {attempt + 1}/{self.max_retries + 1}). "
                    f"{'Returning 0.' if is_last else 'Retrying...'}"
                )
                if is_last:
                    return 0
            except asyncio.CancelledError:
                if future is not None and not future.done():
                    future.add_done_callback(lambda _: self._capacity.release())
                    release_capacity = False
                raise
            except BrokenProcessPool:
                logger.warning(
                    f"ProcessPoolExecutor broken (attempt {attempt + 1}/{self.max_retries + 1}). "
                    "Attempting to recreate..."
                )
                # On BrokenProcessPool (often SIGALRM-SIGKILL hard kill from
                # MathVerifyWorker hang), recreate the pool so subsequent reward
                # calls have a fresh worker — but return 0 for THIS episode
                # rather than re-raising, so the rollout still completes and
                # the trainer's batch can fill. This implements the user spec:
                # "math_verify timeout → auto-kill → assign reward=0".
                if (
                    self._recreate_executor(
                        self._executor_key, self.max_workers, executor
                    )
                    is None
                ):
                    return 0
                if is_last:
                    return 0
            except Exception:
                logger.exception(
                    f"Reward computation error (attempt {attempt + 1}/{self.max_retries + 1})"
                )
                if is_last:
                    raise
            finally:
                if capacity_acquired and release_capacity:
                    self._capacity.release()

        return 0
